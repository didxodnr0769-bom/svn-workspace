import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (file) => readFile(path.join(root, file), 'utf8');
const json = async (file) => JSON.parse(await read(file));
const [manifest, lock, overrides] = await Promise.all([
  json('package.json'), json('package-lock.json'), json('licenses/overrides.json'),
]);
const mode = process.argv[2];
if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) {
  throw new Error('Usage: node scripts/generate-licenses.mjs --write|--check');
}
const sorted = (value) => JSON.stringify(Object.entries(value ?? {}).sort());
if (lock.lockfileVersion !== 3 || sorted(manifest.dependencies) !== sorted(lock.packages[''].dependencies)) {
  throw new Error('package.json and package-lock.json dependencies differ. Update the lockfile first.');
}
if (manifest.license !== 'MIT' || lock.packages[''].license !== manifest.license) {
  throw new Error('Keep the project MIT license metadata in package.json and package-lock.json in sync.');
}

async function installedPackage(location, locked) {
  const installed = await json(`${location}/package.json`);
  if (installed.version !== locked.version || installed.license !== locked.license) {
    throw new Error(`${location} differs from package-lock.json. Run npm ci first.`);
  }
  return installed;
}

const sections = [];
// devOptional includes optional development peers such as @types/react; these
// are not runtime packages copied by electron-builder.
const runtime = Object.entries(lock.packages)
  .filter(([location, pkg]) => location && !pkg.dev && !pkg.devOptional)
  .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
for (const [location, locked] of runtime) {
  const pkg = await installedPackage(location, locked);
  const files = (await readdir(path.join(root, location), { withFileTypes: true }))
    .filter((file) => file.isFile() && /^(licen[cs]e|notice|copying)([.-].*)?$/i.test(file.name))
    .map((file) => file.name).sort();
  const texts = [];
  if (files.length) {
    for (const file of files) {
      const contents = await read(`${location}/${file}`);
      if (!contents.trim()) throw new Error(`Empty notice: ${location}/${file}`);
      texts.push(`--- ${file} ---\n\n${contents.trimEnd()}`);
    }
  } else {
    const fallback = overrides[`${pkg.name}@${pkg.version}`];
    if (!fallback) throw new Error(`No full license text for ${pkg.name}@${pkg.version}. Add a version-specific upstream notice.`);
    const contents = await read(`licenses/${fallback.file}`);
    if (!contents.trim()) throw new Error(`Empty notice: licenses/${fallback.file}`);
    texts.push(`Upstream license supplement (omitted from the npm package):\n${fallback.source}\n\n${contents.trimEnd()}`);
  }
  if (!pkg.license || !locked.resolved) throw new Error(`Missing license/source metadata: ${location}`);
  sections.push(`${pkg.name}@${pkg.version}\nLicense: ${pkg.license}\nPackage: ${locked.resolved}\n\n${texts.join('\n\n')}`);
}

const electron = await installedPackage('node_modules/electron', lock.packages['node_modules/electron']);
const electronLicense = await read('node_modules/electron/dist/LICENSE');
const chromiumNotices = await stat(path.join(root, 'node_modules/electron/dist/LICENSES.chromium.html'));
if (!electronLicense.trim() || !chromiumNotices.isFile() || chromiumNotices.size === 0) {
  throw new Error('Electron distribution license files are missing. Reinstall Electron before packaging.');
}
sections.push(`Electron ${electron.version}\nLicense: ${electron.license}\nSource: https://github.com/electron/electron/tree/v${electron.version}\n\n${electronLicense.trimEnd()}`);

const content = `SVN Workspace — Third-party notices

Generated by npm run licenses:generate from package-lock.json and the installed
runtime packages. Regenerate and review this file when dependencies change.
Third-party components retain their own licenses; the project LICENSE does not
replace these notices. Complete supplied license files are reproduced below,
including additional attributions such as Lucide's Feather-derived icons.

Electron bundles Chromium, Node.js and other components with further notices.
The macOS app includes these upstream files in Contents/Resources/licenses/:
  LICENSE.electron.txt
  LICENSES.chromium.html
Keep that directory with the app when redistributing it. In a source checkout,
the Electron notices are available under node_modules/electron/dist/ after npm ci.

${sections.join('\n\n' + '='.repeat(78) + '\n\n')}\n`;
const target = 'THIRD_PARTY_NOTICES.txt';
if (mode === '--write') {
  await writeFile(path.join(root, target), content);
  console.log(`Generated ${target}: ${runtime.length} runtime npm packages + Electron ${electron.version}.`);
} else {
  if (await read(target) !== content) {
    throw new Error(`${target} is stale. Run npm run licenses:generate and review the result.`);
  }
  console.log(`License notices verified: ${runtime.length} runtime npm packages + Electron ${electron.version}.`);
}
